/**
 * コンシェルジュの答えから、画面に**記号として出てしまう** Markdown を落とす。
 *
 * ## 🔴 なぜ要るか（2026-09-23 に実機で踏んだ）
 *
 * 実機の画面にこう出ていた:
 *
 * > 申し訳ありませんが、`**`本日の日付が不明`**` なため、…
 *
 * `concierge_screen.dart` は `SelectableText(msg.text)` ——
 * **素のテキストで描いていて、Markdown を解釈しない。**
 * それでいてシステムプロンプトは「Markdown 装飾は最小限（**太字のみ可**）」と
 * **太字を明示的に許可していた。** 許可された装飾が、そのまま記号として見える。
 *
 * ## 🔴 プロンプトで禁じるだけでは足りない
 *
 * **これはこの機能を降ろした理由そのものと同じ型。**
 * `url-allowlist.ts` の注記が書いているとおり ——
 *
 * > プロンプトの「実在する公式サイトのみ」は**指示であって担保ではない**。
 *
 * 「装飾を使うな」と書いても、モデルは時々使う。**仕組みで落とす。**
 * プロンプト側も揃えてあるので、ここで落ちる件数は本来 0 に近い ——
 * **増えていたら、指示が効いていないという信号**なので数えて返す。
 *
 * ## 🔴 アプリ側で描画する道を選ばなかった理由
 *
 * `concierge_screen.dart` に Markdown 描画を入れても、**次のリリースが
 * 公開されるまで、いま出ている 1.3.1 の利用者には届かない。**
 * サーバ側なら即座に全員に効く（アプリの再ビルドが要らない）。
 */

export type StripMarkdownResult = {
  text: string;
  /** 落とした装飾の数。**0 でないなら、プロンプトの指示が守られていない。** */
  removed: number;
};

/**
 * 🔴 **対になっているものだけ落とす。** 片方しか無い `**` を消しに行くと、
 *    本文を食う危険がある —— 記号が 1 つ残るより悪い。
 * 🔴 **同じ行の中だけ**で対にする。改行をまたがせると、段落を丸ごと飲む。
 * 🔴 **`_` は触らない。** 許可済みの URL に現れる
 *    （例: `mofa.go.jp/mofaj/toko/page22_000043.html`）。
 *    日本語の回答で `__太字__` はまず使われないので、得より害が大きい。
 */
const RULES: ReadonlyArray<readonly [RegExp, string]> = [
  [/^[ \t]{0,3}#{1,6}[ \t]+/gm, ""],      // 見出しの # 記号
  [/\*\*([^*\n]+)\*\*/g, "$1"],           // **太字**
  [/\*([^*\n]+)\*/g, "$1"],               // *斜体*
  [/`([^`\n]+)`/g, "$1"],                 // `コード`
];

export function stripMarkdown(input: string): StripMarkdownResult {
  let text = input;
  let removed = 0;
  for (const [re, to] of RULES) {
    text = text.replace(re, (...args) => {
      removed += 1;
      // 置換文字列は "$1" か "" のどちらかなので、素朴に解決する。
      return to === "" ? "" : String(args[1]);
    });
  }
  return { text, removed };
}

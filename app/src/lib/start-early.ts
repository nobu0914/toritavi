/**
 * 先に走らせておき、**あとで順に await する**ための包み
 * （2026-10-19・夜間検査 7-31 / 7-35）。
 *
 * 入口の読み取りを並べるとき、**始めるのは一度に、判定は元の順に 1 つずつ**
 * 行う。そうすれば DB が落ちたときに返るコードは直列のときと変わらない。
 *
 * 🔴 **未処理の拒否にしない。** 前の判定で先に返った要求では、後ろの
 * Promise を誰も await しない。その Promise が失敗すると Node は
 * 「未処理の拒否」として扱う。ここで空の catch を付けておき、
 * **await した側には元の失敗がそのまま届く**（判定の挙動は変わらない）。
 *
 * 🔴 **書き込みを包まない。** 前の判定で断った要求でも走りきってしまう。
 * 並べてよいのは、断ったら結果を捨てるだけで済む**読み取り**だけ。
 */
export function startEarly<T>(p: Promise<T>): Promise<T> {
  p.catch(() => {});
  return p;
}
